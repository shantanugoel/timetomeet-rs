#!/usr/bin/env node
/* Derive the automatic light theme from the explicit one.
 *
 * There were two hand-written copies of the light tokens: one behind
 * `:root[data-theme="light"]`, one behind `@media (prefers-color-scheme: light)
 * :root:not([data-theme])`. They drifted - the media copy lost --active and --danger - and
 * the failure only appeared for visitors who never pressed the theme button, which is
 * everybody on their first visit. A token that exists in one selector and not the other is
 * invisible to any test that sets data-theme, so the fix cannot be "remember to update
 * both"; it has to be that there is only one.
 *
 *   node tools/gen-auto-theme.mjs --write dist/style/app.css
 *   node tools/gen-auto-theme.mjs --check dist/style/app.css
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'app', 'style', 'app.css');
const MARK = '/* AUTO-LIGHT (generated by tools/gen-auto-theme.mjs - do not edit) */';

function block(css, selector) {
  const at = css.indexOf(selector);
  if (at < 0) throw new Error(`no block for ${selector}`);
  const open = css.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}') {
      depth--;
      if (!depth) return css.slice(open + 1, i);
    }
  }
  throw new Error(`unbalanced block for ${selector}`);
}

export function autoLightBlock(css) {
  // Comments carry the reasoning; they are not declarations.
  const body = block(css, ':root[data-theme="light"]').replace(/\/\*[\s\S]*?\*\//g, '');
  const decls = [...body.matchAll(/([-\w]+)\s*:\s*([^;]+);/g)]
    .map(([, name, value]) => `    ${name}: ${value.trim()};`)
    .join('\n');
  if (!decls.trim()) throw new Error('light theme block declares nothing');
  // `:not([data-theme])` keeps an explicit choice authoritative; the media query only
  // speaks for people who have never expressed one.
  return `${MARK}\n@media (prefers-color-scheme: light) {\n  :root:not([data-theme]) {\n${decls}\n  }\n}\n`;
}

const argv = process.argv.slice(2);
const flag = (name) => {
  const i = argv.indexOf(name);
  return i < 0 ? null : argv[i + 1];
};
const src = readFileSync(SRC, 'utf8');
const want = autoLightBlock(src);
if (src.includes('@media (prefers-color-scheme')) {
  console.error('app/style/app.css must not contain a @media (prefers-color-scheme) theme block; it is generated.');
  process.exit(1);
}
const target = flag('--write') || flag('--check');
if (!target) {
  process.stdout.write(want);
  process.exit(0);
}
const have = readFileSync(target, 'utf8');
const at = have.indexOf(MARK);
if (flag('--write')) {
  const base = at < 0 ? have : have.slice(0, at);
  writeFileSync(target, base.replace(/\s*$/, '\n\n') + want);
  console.log(`auto-light theme written · ${want.split('\n').length - 3} declarations`);
} else {
  if (at < 0) {
    console.error(`${target} is missing the generated auto-light block`);
    process.exit(1);
  }
  if (!have.slice(at).startsWith(want)) {
    console.error(`${target} has a stale auto-light block; re-run the build`);
    process.exit(1);
  }
  console.log('auto-light theme matches the light theme block');
}
